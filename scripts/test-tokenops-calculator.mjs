import { readFile } from 'node:fs/promises';
import { calculateApiCost } from '../assets/js/pages/tokenops-api-calculator.js';
import { calculateCopilotCredits, allowanceForPlan } from '../assets/js/pages/tokenops-copilot-calculator.js';
const api=JSON.parse(await readFile('assets/data/tokenops-api-models.json','utf8'));
const copilot=JSON.parse(await readFile('assets/data/tokenops-copilot-models.json','utf8'));
const plans=JSON.parse(await readFile('assets/data/tokenops-copilot-plans.json','utf8'));
const gpt=api.providers.find(p=>p.id==='openai').models.find(m=>m.id==='gpt-5.4-mini');
const apiResult=calculateApiCost(gpt,{inputTokens:1000,cachedInputTokens:0,cacheWriteTokens:0,outputTokens:200,requestsPerDay:1,daysPerMonth:30},'standard','auto');
if(!apiResult || Math.abs(apiResult.perRequest - 0.00165) > 1e-10) throw new Error('API formula test failed');
const model=copilot.models.find(m=>m.name==='GPT-5 mini');
const plan=plans.individualPlans.find(p=>p.id==='pro');
const copilotResult=calculateCopilotCredits(model,{featureId:'chat',inputTokens:1000,cachedInputTokens:0,cacheWriteTokens:0,outputTokens:200,interactionsPerMonth:100,autoSelection:false},plan,copilot);
if(Math.abs(copilotResult.monthlyCredits - 6.5) > 1e-10) throw new Error('Copilot formula test failed');
if(allowanceForPlan(plan,1,false)!==1500) throw new Error('Plan allowance test failed');
const noBill=calculateCopilotCredits(model,{featureId:'code-completions',inputTokens:999999,outputTokens:999999,interactionsPerMonth:999,autoSelection:false},plan,copilot);
if(noBill.monthlyCredits!==0) throw new Error('Non-billed completion test failed');
console.log('Calculator tests passed.');
