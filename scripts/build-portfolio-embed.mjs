import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const output = 'dist/portfolio-embed';
const dataFiles = [
  'tokenops-api-models.json',
  'tokenops-copilot-models.json',
  'tokenops-copilot-plans.json',
  'tokenops-scenarios.json',
  'tokenops-learning-content.json',
  'tokenops-copilot-legacy-pru.json',
  'tokenops-announcements.json'
];

await rm(output, { recursive: true, force: true });
await mkdir(join(output, 'data'), { recursive: true });
await cp('src/portfolio-embed/tokenops-lab.js', join(output, 'tokenops-lab.js'));
await cp('src/portfolio-embed/tokenops-lab.css', join(output, 'tokenops-lab.css'));
await cp('portfolio/manifest.json', join(output, 'manifest.json'));
for (const filename of dataFiles) {
  await cp(join('assets/data', filename), join(output, 'data', filename));
}
await writeFile(join(output, '.built-by-tokenops'), 'Portfolio embed output generated by npm run build:embed\n', 'utf8');
console.log(`Built ${output} with ${dataFiles.length} registry/support files.`);
